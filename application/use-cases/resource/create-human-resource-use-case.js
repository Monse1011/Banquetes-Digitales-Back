const { Resource } = require("../../../domain/entities/resource/resource");
const { ResourceType } = require("../../../domain/enums/resource/resource-type");
const ResourceValidationException = require("../../../domain/exceptions/resource/resource-validation-exception");
const DuplicateResourceException = require("../../../domain/exceptions/resource/duplicate-resource-exception");
const HumanResourceRequestDto = require("../../dto/resource/human-resource-request-dto");
const { ensureActiveOperativeRole } = require("../../services/resource/human-resource-guards");

// Un recurso humano representa a una sola persona.
const HUMAN_RESOURCE_QUANTITY = 1;

class CreateHumanResourceUseCase {
  constructor(resourceRepository, operativeRoleRepository) {
    this.resourceRepository = resourceRepository;
    this.operativeRoleRepository = operativeRoleRepository;
  }

  async execute(input = {}) {
    const dto = new HumanResourceRequestDto(input.name, input.operativeRoleId);
    const errors = dto.validate();

    if (Object.keys(errors).length > 0) {
      throw new ResourceValidationException(errors);
    }

    await ensureActiveOperativeRole(this.operativeRoleRepository, dto.operative_role_id);

    const name = dto.name.trim();

    // RF-1.2.8.7: un duplicado solo se registra con la confirmación del Administrador.
    if (input.confirmDuplicate !== true) {
      const isDuplicate = await this.resourceRepository.existsActiveByNameAndRole(
        ResourceType.HUMAN,
        name,
        dto.operative_role_id
      );

      if (isDuplicate) {
        throw new DuplicateResourceException();
      }
    }

    const now = new Date();

    // RF-1.2.8.1: tipo "Humano" asignado automáticamente y estado inicial "Activo".
    const createdResource = await this.resourceRepository.create(
      new Resource(
        undefined, // id will be generated by the repository
        name,
        ResourceType.HUMAN,
        dto.operative_role_id,
        HUMAN_RESOURCE_QUANTITY,
        null, // unitCost does not apply to human resources
        true,
        now,
        now,
        null
      )
    );

    return { id: createdResource.id };
  }
}

module.exports = { CreateHumanResourceUseCase };
