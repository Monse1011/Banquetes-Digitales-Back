const { Resource } = require("../../../domain/entities/resource/resource");
const ResourceValidationException = require("../../../domain/exceptions/resource/resource-validation-exception");
const InventoryResourceRequestDto = require("../../dto/resource/inventory-resource-request-dto");
const { ensureUniqueName } = require("../../services/resource/resource-guards");

// Registro de recursos materiales (2.9) y logísticos (2.10); una instancia por tipo.
class CreateInventoryResourceUseCase {
  constructor(resourceRepository, type) {
    this.resourceRepository = resourceRepository;
    this.type = type;
  }

  async execute(input = {}) {
    const dto = new InventoryResourceRequestDto(input.name, input.quantity, input.unitCost);
    const errors = dto.validate();

    if (Object.keys(errors).length > 0) {
      throw new ResourceValidationException(errors);
    }

    const name = dto.name.trim();

    await ensureUniqueName(this.resourceRepository, this.type, name);

    const now = new Date();

    // RF-1.2.9.1 / RF-1.2.10.1: tipo asignado automáticamente y estado inicial "Activo".
    const createdResource = await this.resourceRepository.create(
      new Resource(
        undefined, // id will be generated by the repository
        name,
        this.type,
        null, // operativeRoleId only applies to human resources
        dto.quantity,
        dto.unit_cost,
        true,
        now,
        now,
        null
      )
    );

    return { id: createdResource.id };
  }
}

module.exports = { CreateInventoryResourceUseCase };
