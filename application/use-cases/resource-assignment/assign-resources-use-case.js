const {
  ResourceAssignment,
} = require("../../../domain/entities/resource-assignment/resource-assignment");
const { ResourceType } = require("../../../domain/enums/resource/resource-type");
const { AssignmentStatus } = require("../../../domain/enums/resource-assignment/assignment-status");
const {
  ResourceSufficiency,
} = require("../../../domain/enums/resource-assignment/resource-sufficiency");
const {
  ResourceAssignmentMessages,
} = require("../../../domain/constants/resource-assignment-messages");
const ResourceAssignmentValidationException = require("../../../domain/exceptions/resource-assignment/resource-assignment-validation-exception");
const ResourceAvailabilityChangedException = require("../../../domain/exceptions/resource-assignment/resource-availability-changed-exception");
const AssignResourcesRequestDto = require("../../dto/resource-assignment/assign-resources-request-dto");
const {
  findConfirmableRequest,
} = require("../../services/resource-assignment/request-access-guard");
const {
  blockingPeriod,
  availableQuantity,
} = require("../../services/resource-assignment/resource-availability");
const { normalizeObservation } = require("../../services/resource-assignment/assignment-review");

// Un recurso humano representa a una sola persona (RF-1.2.8.1).
const HUMAN_RESOURCE_QUANTITY = 1;

// Función 3.2 - POST /api/logistics/requests/:id/resources. Cada recurso del body es un recurso
// solicitado: si la cantidad disponible alcanza queda asignado como "Provisional"; si no, se
// registra "Insuficiente" sin asignación (RF-2.3.2.6, RF-2.3.2.7, RF-2.3.2.11).
class AssignResourcesUseCase {
  constructor(
    resourceRepository,
    reservationRequestRepository,
    resourceAssignmentRepository,
    resourceConfirmationRepository
  ) {
    this.resourceRepository = resourceRepository;
    this.reservationRequestRepository = reservationRequestRepository;
    this.resourceAssignmentRepository = resourceAssignmentRepository;
    this.resourceConfirmationRepository = resourceConfirmationRepository;
  }

  async execute(requestId, user, input = {}) {
    const dto = new AssignResourcesRequestDto(input.data, input.observations);
    const errors = dto.validate();

    if (Object.keys(errors).length > 0) {
      throw new ResourceAssignmentValidationException(errors);
    }

    const request = await findConfirmableRequest(
      this.reservationRequestRepository,
      requestId,
      user
    );
    const resources = await Promise.all(
      dto.data.map((item) => this.resourceRepository.findById(item.resource_id))
    );
    const items = dto.data.map((item) => ({
      resourceId: item.resource_id,
      quantity: item.quantity,
      usageStart: item.usage_start ? new Date(item.usage_start) : request.eventDateTime,
      usageEnd: item.usage_end ? new Date(item.usage_end) : request.eventEndTime,
      observation: normalizeObservation(item.observation),
    }));

    this.ensureAssignable(items, resources, request);

    // RF-2.3.2.12: se consideran fecha y hora de ambos eventos más el margen de 3 horas.
    const period = blockingPeriod(request.eventDateTime, request.eventEndTime);
    const blocking = await this.resourceAssignmentRepository.findBlocking(
      items.map((item) => item.resourceId),
      period,
      request.requestId
    );
    const now = new Date();

    const assignments = items.map((item, index) => {
      const available = availableQuantity(resources[index], blocking, period);
      const isSufficient = available >= item.quantity;

      return new ResourceAssignment(
        undefined, // id will be generated by the repository
        request.requestId,
        item.resourceId,
        isSufficient ? item.quantity : 0, // RF-2.3.2.7: sin asignaciones parciales
        item.quantity,
        available,
        isSufficient ? ResourceSufficiency.SUFFICIENT : ResourceSufficiency.INSUFFICIENT,
        AssignmentStatus.PROVISIONAL,
        item.usageStart,
        item.usageEnd,
        request.eventDateTime,
        request.eventEndTime,
        item.observation,
        user.id,
        now
      );
    });

    // RF-2.3.2.13 / RF-2.3.2.22: otra asignación cambió la disponibilidad tras la consulta.
    if (!(await this.resourceAssignmentRepository.saveProvisional(assignments, blocking))) {
      throw new ResourceAvailabilityChangedException();
    }

    if (input.observations !== undefined) {
      await this.resourceConfirmationRepository.savePendingObservations(
        request.requestId,
        normalizeObservation(input.observations)
      );
    }
  }

  ensureAssignable(items, resources, request) {
    const errors = {};

    items.forEach((item, index) => {
      const resource = resources[index];

      if (!resource || !resource.isActive) {
        errors[`data[${index}].resource_id`] = ResourceAssignmentMessages.RESOURCE_NOT_AVAILABLE;
      } else if (
        resource.type === ResourceType.HUMAN &&
        item.quantity !== HUMAN_RESOURCE_QUANTITY
      ) {
        errors[`data[${index}].quantity`] = ResourceAssignmentMessages.HUMAN_QUANTITY_INVALID;
      }

      if (
        item.usageStart >= item.usageEnd ||
        item.usageStart < request.eventDateTime ||
        item.usageEnd > request.eventEndTime
      ) {
        errors[`data[${index}].usage_start`] = ResourceAssignmentMessages.USAGE_PERIOD_INVALID;
      }
    });

    if (Object.keys(errors).length > 0) {
      throw new ResourceAssignmentValidationException(errors);
    }
  }
}

module.exports = { AssignResourcesUseCase };
