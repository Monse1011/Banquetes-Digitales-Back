const {
  ResourceAssignment,
} = require("../../../domain/entities/resource-assignment/resource-assignment");
const { ResourceType } = require("../../../domain/enums/resource/resource-type");
const { AssignmentStatus } = require("../../../domain/enums/resource-assignment/assignment-status");
const {
  ResourceSufficiency,
} = require("../../../domain/enums/resource-assignment/resource-sufficiency");
const {
  ResourceAssignmentMessages,
} = require("../../../domain/constants/resource-assignment-messages");
const ResourceAssignmentValidationException = require("../../../domain/exceptions/resource-assignment/resource-assignment-validation-exception");
const ResourceAvailabilityChangedException = require("../../../domain/exceptions/resource-assignment/resource-availability-changed-exception");
const {
  AssignResourcesRequestDto,
  normalizeObservation,
} = require("../../dto/resource-assignment/assign-resources-request-dto");
const {
  findConfirmableRequest,
} = require("../../services/resource-assignment/request-access-guard");
const {
  blockingPeriod,
  availableQuantity,
} = require("../../services/resource-assignment/resource-availability");

// Un recurso humano representa a una sola persona (RF-1.2.8.1).
const HUMAN_RESOURCE_QUANTITY = 1;

// Función 3.2 - Asignar recursos a la solicitud (POST /api/logistics/requests/:id/resources).
// Cada recurso del body es un recurso solicitado: si la cantidad disponible alcanza, queda
// asignado como "Provisional" por la cantidad solicitada; si no, se registra "Insuficiente" sin
// asignación, con su observación (RF-2.3.2.6, RF-2.3.2.7, RF-2.3.2.11).
class AssignResourcesUseCase {
  constructor(resourceRepository, reservationRequestRepository, resourceAssignmentRepository) {
    this.resourceRepository = resourceRepository;
    this.reservationRequestRepository = reservationRequestRepository;
    this.resourceAssignmentRepository = resourceAssignmentRepository;
  }

  async execute(requestId, user, input = {}) {
    const dto = new AssignResourcesRequestDto(input.items, input.observations);
    const formatErrors = dto.validate();

    if (Object.keys(formatErrors).length > 0) {
      throw new ResourceAssignmentValidationException(formatErrors);
    }

    const request = await findConfirmableRequest(
      this.reservationRequestRepository,
      requestId,
      user
    );
    const items = dto.toItems();
    const resources = await Promise.all(
      items.map((item) => this.resourceRepository.findById(item.resourceId))
    );

    this.ensureValidItems(items, resources, request);

    // RF-2.3.2.12: se consideran fecha y hora de ambos eventos más el margen de 3 horas.
    const period = blockingPeriod(request.eventDateTime, request.eventEndTime);
    const { assignments, versions } = await this.resourceAssignmentRepository.findBlocking(
      items.map((item) => item.resourceId),
      period,
      request.requestId
    );
    const now = new Date();

    const provisionalAssignments = items.map((item, index) => {
      const available = availableQuantity(resources[index], assignments, period);

      return new ResourceAssignment(
        undefined, // id will be generated by the repository
        request.requestId,
        item.resourceId,
        item.quantity,
        available,
        available >= item.quantity
          ? ResourceSufficiency.SUFFICIENT
          : ResourceSufficiency.INSUFFICIENT,
        AssignmentStatus.PROVISIONAL,
        request.eventDateTime,
        request.eventEndTime,
        item.usageStart ?? request.eventDateTime,
        item.usageEnd ?? request.eventEndTime,
        item.observation,
        user.id,
        now
      );
    });

    // RF-2.3.2.13 / RF-2.3.2.22: otra asignación cambió la disponibilidad tras la consulta.
    const saved = await this.resourceAssignmentRepository.saveProvisional(
      request.requestId,
      provisionalAssignments,
      versions
    );

    if (!saved) {
      throw new ResourceAvailabilityChangedException();
    }

    if (input.observations !== undefined) {
      await this.resourceAssignmentRepository.savePendingObservations(
        request.requestId,
        normalizeObservation(input.observations)
      );
    }
  }

  ensureValidItems(items, resources, request) {
    const errors = {};

    items.forEach((item, index) => {
      const resource = resources[index];
      const field = (name) => `data[${index}].${name}`;

      if (!resource || !resource.isActive) {
        errors[field("resource_id")] = ResourceAssignmentMessages.RESOURCE_NOT_AVAILABLE;
      } else if (
        resource.type === ResourceType.HUMAN &&
        item.quantity !== HUMAN_RESOURCE_QUANTITY
      ) {
        errors[field("quantity")] = ResourceAssignmentMessages.HUMAN_QUANTITY_INVALID;
      }

      const usageStart = item.usageStart ?? request.eventDateTime;
      const usageEnd = item.usageEnd ?? request.eventEndTime;

      if (
        usageStart >= usageEnd ||
        usageStart < request.eventDateTime ||
        usageEnd > request.eventEndTime
      ) {
        errors[field("usage_start")] = ResourceAssignmentMessages.USAGE_PERIOD_INVALID;
      }
    });

    if (Object.keys(errors).length > 0) {
      throw new ResourceAssignmentValidationException(errors);
    }
  }
}

module.exports = { AssignResourcesUseCase };
